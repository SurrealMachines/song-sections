"""End-to-end golden audio (Task 10), written ONLY to .dev/golden/ (gitignored, never committed).

- flim-44k.wav, icl-44k.wav: $SPIKE/ref/{flim,inner-city-life}.flac decoded to float32 WAV (the PyTorch baseline's
  input, so out/baseline/<name>.json applies to them as-is).
- flim-48k.wav: flim-44k resampled 44.1 -> 48 kHz with julius.resample_frac (Live's common project rate), float32.
- flim-44k-m12.wav: flim-44k at -12 dB (x 10^(-12/20) in float32), the Task 9 reviewer's level experiment (I1).

Large (about 340 MB together) but cheap to rebuild, so they are regenerated by `npm run fixtures` like the others.
"""
from pathlib import Path

import julius
import numpy as np
import soundfile as sf
import torch

from common import SPIKE

OUT = Path(__file__).resolve().parents[2] / ".dev" / "golden"
TRACKS = {"flim": "flim.flac", "icl": "inner-city-life.flac"}


def write(path: Path, audio: np.ndarray, rate: int) -> None:
    """audio: (frames, channels) float32."""
    assert audio.dtype == np.float32, audio.dtype
    sf.write(str(path), audio, rate, subtype="FLOAT", format="WAV")
    print(f"   {path.name}: {audio.shape[0]} frames x {audio.shape[1]} ch @ {rate} Hz")


OUT.mkdir(parents=True, exist_ok=True)
decoded = {}
for name, flac in TRACKS.items():
    audio, rate = sf.read(str(SPIKE / "ref" / flac), dtype="float32", always_2d=True)
    assert rate == 44100, (flac, rate)
    decoded[name] = audio
    write(OUT / f"{name}-44k.wav", audio, 44100)

write(OUT / "flim-44k-m12.wav", (decoded["flim"] * np.float32(10 ** (-12 / 20))).astype(np.float32), 44100)

# julius works along the last axis: (channels, frames).
x = torch.from_numpy(np.ascontiguousarray(decoded["flim"].T))
y = julius.resample_frac(x, 44100, 48000)
write(OUT / "flim-48k.wav", np.ascontiguousarray(y.numpy().T.astype(np.float32)), 48000)
